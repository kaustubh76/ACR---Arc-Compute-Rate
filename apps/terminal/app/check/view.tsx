export function CheckView() {
  const [unit, setUnit] = useState<Unit>("$/1k tokens");
  const [billed, setBilled] = useState("");
  const [quantity, setQuantity] = useState("");
  const [vendor, setVendor] = useState("");
  const [problem, setProblem] = useState<string | null>(null);
  const [query, setQuery] = useState<string | null>(null);

  const { check, error, loading } = useParCheck(query);
  const c = check?.data ?? null;

  /* A LINKED RESULT MUST SURVIVE A RELOAD, so the URL is the source on mount —
     the same contract /tape keeps for `?payer=`. Everything is re-validated on
     the way back in: a hand-edited URL cannot poison state, it just does not
     load. Plain `history.replaceState` rather than the router, because this is
     one page's own address and a navigation would remount the form.

     `react-hooks/set-state-in-effect` warns here and the warning is accepted,
     as it is at `app/tape/view.tsx`: `window.location` does not exist during
     SSR, so state seeded from the address cannot be an initializer. It runs
     once, on mount, and bails before touching state unless every field
     validates. */
  useEffect(() => {
    const q = new URLSearchParams(window.location.search);
    const u = q.get("unit") ?? "";
    const b = Number(q.get("billed_usdc"));
    const n = Number(q.get("quantity"));
    const v = (q.get("vendor") ?? "").trim();
    if (!isUnit(u) || !Number.isFinite(b) || b <= 0 || !Number.isFinite(n) || n <= 0) return;
    if (v && !ADDRESS.test(v)) return;
    setUnit(u);
    setBilled(String(b));
    setQuantity(String(n));
    setVendor(v);
    setQuery(build(u, b, n, v));
  }, []);

  function build(u: string, b: number, n: number, v: string): string {
    const p = new URLSearchParams({
      unit: u,
      billed_usdc: String(b),
      quantity: String(n),
    });
    if (v) p.set("vendor", v);
    return p.toString();
  }

  function submit() {
    const b = Number(billed.trim());
    const n = Number(quantity.trim());
    const v = vendor.trim();
    if (!Number.isFinite(b) || b <= 0) {
      setProblem("The billed amount has to be a number above zero.");
      return;
    }
    if (!Number.isFinite(n) || n <= 0) {
      setProblem("The quantity has to be a number above zero.");
      return;
    }
    if (v && !ADDRESS.test(v)) {
      setProblem("That is not an address. It needs 0x and 40 characters, or leave it empty.");
      return;
    }
    setProblem(null);
    const q = build(unit, b, n, v);
    setQuery(q);
    const url = new URL(window.location.href);
    url.search = q;
    window.history.replaceState(null, "", url.toString());
  }

  // What the press was actually asked, reconstructed for display from the same
  // parts the proxy forwards. Shown rather than described, because the point of
  // the section is that a reader can run it.
  const requestPath = query
    ? `/par?${query.replace(/%2F/g, "%2F")}`
    : "";

  return (
    <>
      <section className="section">
        <div className="section-head">
          <h2>
            <Ed x="Check a bill" p="Is this bill fair?" />
          </h2>
          <span className="label">{INDEX_FOR_UNIT[unit]}</span>
        </div>
        <p className="standfirst standfirst-block">
          <Ed
            x="Give it one invoice and it answers against published list prices from sellers we do not operate, with a link to every price it used. No account, no key, nothing stored."
            p="Type in one bill. We compare it to real published prices and show you every one we used."
          />
        </p>
        <div className="panel panel-pad">
          <Form
            unit={unit}
            billed={billed}
            quantity={quantity}
            vendor={vendor}
            onUnit={(u) => {
              setUnit(u);
              setProblem(null);
            }}
            onBilled={(v) => {
              setBilled(v);
              setProblem(null);
            }}
            onQuantity={(v) => {
              setQuantity(v);
              setProblem(null);
            }}
            onVendor={(v) => {
              setVendor(v);
              setProblem(null);
            }}
            onSubmit={submit}
            problem={problem}
            busy={loading}
          />
        </div>
      </section>

      {/* THREE STATES, not two, and the middle one is the press being down.
          /spend spent weeks telling readers a business did not exist because
          its proxy could not distinguish "nothing" from "we could not ask".
          The same distinction is drawn here from the start: a 422 is a problem
          with the bill, a 503 is a problem with us, and neither is a verdict. */}
      {error && !c ? (
        <section className="section">
          <div className="panel panel-pad">
            <p className="standfirst">
              {error.status === 422 ? (
                <Ed
                  x="That bill could not be read, so nothing was priced. Check the amount and the quantity."
                  p="We could not read that bill, so we priced nothing. Check the numbers."
                />
              ) : null}
            </p>
            {/* A DEAD END UNTIL NOW, on the surface that most needed a way out.
                This page hand-rolled its own absent sentence while /spend and
                /traction used `WhyEmpty` — so a stranger arriving with a bill,
                on the default chain, where /par does not exist, was told the
                truth and given nowhere to go. `WhyEmpty` carries the switch.
                The 422 above stays its own branch: a bill we could not read is
                a fact about the bill, and no chain change fixes it. */}
            {error.status !== 422 ? (
              <WhyEmpty
                upstream={error.upstream}
                what="this benchmark"
                plainWhat="the price check"
              />
            ) : null}
          </div>
        </section>
      ) : null}

      {c ? <Verdict c={c} requestPath={requestPath} /> : null}
    </>
  );
}
