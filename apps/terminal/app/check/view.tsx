/* Bring your own bill.
 *
 * `/par` has always answered a stranger's invoice with no onboarding, and
 * `lib/endpoints.ts` has always advertised it as runnable. What a reader could
 * not do was USE it: the only way to exercise it was to hand-build a query
 * string with a percent-encoded `$/1k tokens` in it.
 *
 * This page is evidence, not a funnel. There is nothing to sign up for and
 * nothing is captured. The thing it is trying to earn is one specific kind of
 * trust: that the comparison is against somebody else's published prices and
 * that you can go and look at them. So every row carries its own link, and the
 * state of the basket those prices came from is stated on the page rather than
 * implied by a verdict.
 */

